def polish(text):
    if not isinstance(text, str):
        return text
    import re
    out = text
    for key, value in ACCENT_WORDS.items():
        out = re.sub(r"(?<![A-Za-z\u00c0-\u017f])" + re.escape(key) + r"(?![A-Za-z\u00c0-\u017f])", value, out)
    return out


def lookup(table, cid, abbr, default=None):
    if "%s|%s" % (cid, abbr) in table:
        return table["%s|%s" % (cid, abbr)]
    target = fold("%s|%s" % (cid, abbr))
    for key, value in table.items():
        if fold(key) == target:
            return value
    return default


